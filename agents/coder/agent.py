import os
import re
from typing import Dict, Any, List
from agents.coder.tools import CoderTools
from agents.coder.prompts import CODER_SYSTEM_PROMPT
from llm.provider import get_llm_provider, LLMMessage


class CoderAgent:
    """
    Coder Agent: Performs controlled code modifications based on the Planner Agent's output
    and produces unified diffs for human developer review and approval.
    Uses a configurable LLM provider (Gemini / OpenAI / Anthropic) for intelligent code generation.
    Includes security guards against path traversal, secret modification, and oversized payloads.
    """

    MAX_FILES_PER_RUN = 5
    MAX_CHANGES_LIMIT = 20
    SENSITIVE_PATTERNS = {
        ".env", ".env.local", ".env.production", ".env.development",
        "id_rsa", "id_ed25519", "credentials.json", "service_account.json",
        "secret.key", "private.key", ".pem", ".pfx", ".pkcs12"
    }

    def __init__(self, root_dir: str):
        self.root_dir = os.path.realpath(os.path.abspath(root_dir))
        self.tools = CoderTools(self.root_dir)
        self._llm = None  # lazy init

    @property
    def llm(self):
        if self._llm is None:
            self._llm = get_llm_provider()
        return self._llm

    def _is_safe_path(self, path: str) -> bool:
        if not path or not isinstance(path, str) or "\0" in path:
            return False
        if ".." in path or path.startswith("/") or path.startswith("\\"):
            return False
        base_name = os.path.basename(path).lower()
        if any(pat in base_name for pat in self.SENSITIVE_PATTERNS):
            return False
        return True

    def _generate_code_with_llm(
        self,
        rel_path: str,
        task_request: str,
        existing_content: str,
        plan_context: str,
    ) -> str:
        """
        Asks the LLM to generate or modify code for the given file.
        Falls back to the heuristic stub if the LLM is unavailable.
        """
        is_new = not existing_content.strip()
        verb = "Create" if is_new else "Modify"

        ext = os.path.splitext(rel_path)[1]
        language_hint = {
            ".py": "Python", ".ts": "TypeScript", ".tsx": "TypeScript React",
            ".js": "JavaScript", ".jsx": "JavaScript React",
        }.get(ext, "code")

        user_prompt = f"""{verb} the file `{rel_path}` ({language_hint}).

Task: {task_request}

Plan context:
{plan_context}

{'Existing file content (modify this):' if not is_new else 'This is a new file. Write it from scratch.'}
{existing_content[:3000] if existing_content else '(empty)'}

Requirements:
- Only output the complete, final file content (no explanations).
- Keep existing functionality intact when modifying.
- Follow the existing code style, naming conventions, and import patterns.
- Do NOT expose secrets or remove security guards.
- If this is a Python file, include proper type hints and docstrings.
- If this is TypeScript/React, use proper types and follow component patterns.
"""

        try:
            response = self.llm.chat(
                messages=[LLMMessage(role="user", content=user_prompt)],
                system_prompt=CODER_SYSTEM_PROMPT,
                temperature=0.15,
                max_tokens=4096,
            )

            text = response.content.strip()

            # Skip stub / empty responses
            if response.provider == "stub" or "[StubProvider]" in text or not text:
                return self._heuristic_content(rel_path, task_request, existing_content)

            # Strip markdown code fences if present
            text = re.sub(r'^```[a-zA-Z]*\n?', '', text, flags=re.MULTILINE)
            text = re.sub(r'\n?```$', '', text, flags=re.MULTILINE)
            return text.strip()

        except Exception:
            return self._heuristic_content(rel_path, task_request, existing_content)

    def _heuristic_content(
        self, rel_path: str, task_request: str, existing_content: str
    ) -> str:
        """Fallback heuristic modification when LLM is unavailable."""
        if not existing_content.strip():
            clean_name = rel_path.split('/')[-1].replace('.', '_')
            return f"""# New Module: {rel_path}
# Auto-generated by Coder Agent for task: {task_request}

def handle_{clean_name}_feature():
    \"\"\"
    Implementation of {task_request}
    \"\"\"
    return {{"status": "active", "task": "{task_request}"}}
"""
        else:
            comment_marker = "//" if rel_path.endswith((".ts", ".tsx", ".js", ".jsx")) else "#"
            return (
                existing_content.rstrip()
                + f"\n\n{comment_marker} AI Developer OS Coder Agent: Implemented feature for '{task_request}'\n"
            )

    def execute_modification(self, plan: Dict[str, Any]) -> Dict[str, Any]:
        if not plan or not isinstance(plan, dict):
            plan = {}

        raw_task = plan.get("task_request", "Update software functionality")
        task_request = re.sub(r"[\x00-\x1f\x7f-\x9f]", " ", str(raw_task)).strip()[:5000]

        # Build plan context for LLM
        steps = plan.get("implementation_steps", [])
        plan_context = "\n".join(str(s) for s in steps[:5]) if steps else "No structured steps provided."

        affected_files_detailed = plan.get("affected_files_detailed", [])
        if affected_files_detailed and isinstance(affected_files_detailed, list):
            candidate_files = [f.get("path", "") for f in affected_files_detailed if isinstance(f, dict)]
        else:
            candidate_files = plan.get("affected_files", ["apps/web/src/app/login/page.tsx", "apps/api/main.py"])

        target_files = [f for f in candidate_files if self._is_safe_path(f)][:self.MAX_FILES_PER_RUN]
        if not target_files:
            target_files = ["apps/api/main.py"]

        changes = []
        total_additions = 0
        total_deletions = 0
        llm_provider_used = None

        for rel_path in target_files:
            existing_content = self.tools.read_file(rel_path)
            is_error = existing_content.startswith("Error") or existing_content.startswith("Security Error")
            is_new = is_error or not existing_content.strip()
            if is_error:
                existing_content = ""

            change_type = "created" if is_new else "modified"

            # Generate code via LLM (with heuristic fallback)
            modified_content = self._generate_code_with_llm(
                rel_path, task_request, existing_content, plan_context
            )

            # Track provider used
            try:
                if llm_provider_used is None:
                    llm_provider_used = self.llm.__class__.__name__
            except Exception:
                pass

            diff = self.tools.generate_diff(rel_path, existing_content, modified_content)

            adds = sum(1 for line in diff.splitlines() if line.startswith("+") and not line.startswith("+++"))
            dels = sum(1 for line in diff.splitlines() if line.startswith("-") and not line.startswith("---"))
            total_additions += adds
            total_deletions += dels

            changes.append({
                "file_path": rel_path,
                "change_type": change_type,
                "additions": adds,
                "deletions": dels,
                "old_content": existing_content,
                "new_content": modified_content,
                "diff": diff
            })

        return {
            "status": "success",
            "task_request": task_request,
            "files_modified_count": len(changes),
            "total_additions": total_additions,
            "total_deletions": total_deletions,
            "changes": changes,
            "approval_required": True,
            "llm_provider": llm_provider_used,
        }

    def apply_changes(self, changes: List[Dict[str, Any]]) -> Dict[str, Any]:
        if not changes or not isinstance(changes, list):
            return {
                "status": "error",
                "message": "No valid changes provided to apply.",
                "applied_files": []
            }

        applied_results = []
        for change in changes[:self.MAX_CHANGES_LIMIT]:
            if not isinstance(change, dict):
                continue
            rel_path = change.get("file_path", "")
            new_content = change.get("new_content", "")
            if not self._is_safe_path(rel_path):
                applied_results.append({
                    "file_path": str(rel_path),
                    "status": "Security Error: Path traversal or sensitive file access denied."
                })
                continue

            if rel_path and new_content is not None:
                res = self.tools.apply_diff_to_file(rel_path, str(new_content))
                applied_results.append({"file_path": rel_path, "status": res})

        return {
            "status": "success",
            "message": f"Successfully processed {len(applied_results)} code changes.",
            "applied_files": applied_results
        }
